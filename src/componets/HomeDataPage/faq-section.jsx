




import { useState } from "react";

const faqs = [
    {
        question: "What is an AI writer website?",
        answer:
            "An AI writer website uses artificial intelligence to help you create written content, from ideas and outlines to polished copy."
    },
    {
        question: "How does AI writing work?",
        answer:
            "AI writing tools use language models to understand your prompt and generate relevant text. Give the tool clear instructions, then review and refine the result."
    },
    {
        question: "What can I use AI writing for?",
        answer:
            "You can use AI writing to draft blog posts, marketing copy, product descriptions, emails, social posts, and many other types of content."
    },
    {
        question: "Is the content generated by AI original?",
        answer:
            "AI generates text in response to your prompt, but it is a good idea to review the result, verify facts, and make edits so the content reflects your own voice and requirements."
    },
    {
        question: "How do I use an AI writer website?",
        answer:
            "Choose the type of content you need, enter a clear prompt with useful details, generate a draft, and edit it until it is ready to use."
    }
];

function Faq() {
    const [openFaq, setOpenFaq] = useState(null);

    return(
        <section className="faq-section">
            <div className="container">

                <div className="row">
                    <div className="col-lg-6 m-auto text-center">
                        <div className="faq-heading">
                            <h6>FAQ</h6>
                            <h2>Frequently asked question</h2>
                        </div>
                    </div>
                </div>

                <div className="row">
                    <div className="col-lg-8 m-auto">
                        <div className="faq-list">
                            {faqs.map((item, index) => {
                                const isOpen = openFaq === index;
                                const answerId = `faq-answer-${index}`;

                                return (
                                    <div className="faq-item" key={item.question}>
                                        <button
                                            className="faq-question"
                                            type="button"
                                            aria-expanded={isOpen}
                                            aria-controls={answerId}
                                            onClick={() =>
                                                setOpenFaq(isOpen ? null : index)
                                            }
                                        >
                                            <span>{item.question}</span>
                                            <span className="faq-icon" aria-hidden="true">
                                                {isOpen ? "−" : "+"}
                                            </span>
                                        </button>
                                        {isOpen && (
                                            <div className="faq-answer" id={answerId}>
                                                <p>{item.answer}</p>
                                            </div>
                                        )}
                                    </div>
                                );
                            })}
                        </div>
                    </div>
                </div>

            </div>
        </section>
    )
    
}

export default Faq;